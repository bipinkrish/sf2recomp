#define FPCR_FZ (SF2C_SIMD_N_1U_B8E6 << SF2C_SIMD_N_24_C235)
#define FPCR_RM (SF2C_SIMD_N_3U_3B80 << SF2C_SIMD_N_22_785F)
#define FPCR_SLOW (FPCR_FZ | FPCR_RM)

